import { apiError, err, ok } from "@officebox/shared";
import { CoreDurableObject, type DoMigration, type RpcResult } from "./core/do/base";

/** The keys the Worker may generate when their Worker secret isn't set (Platform §16, M1b-1). */
export const GENERATED_KEY_NAMES = ["better_auth_secret", "token_hash_key"] as const;
export type GeneratedKeyName = (typeof GENERATED_KEY_NAMES)[number];

/** 32 random bytes, as every generated key is (Platform §16). */
const GENERATED_KEY_BYTES = 32;

/** Where a sign-in key came from when an isolate last resolved it. */
export type RecordedKeySource = "worker_secret" | "generated";

export interface KeySourceChange {
  /** The source recorded before, and since when (epoch ms); null when unchanged or first seen. */
  previous: { source: RecordedKeySource; since: number } | null;
}

function isGeneratedKeyName(name: string): name is GeneratedKeyName {
  return (GENERATED_KEY_NAMES as readonly string[]).includes(name);
}

function randomKey(): string {
  const bytes = crypto.getRandomValues(new Uint8Array(GENERATED_KEY_BYTES));
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

/**
 * Installation-wide system Durable Object (single instance, named "system"; TDD §2.2).
 *
 * - `ping()`: the Durable Object check of `/health` (TDD §7.1) and of setup's required-services check.
 * - `generatedKey(name)` (M1b-1, schema version 2): the **keys generated by the Worker** for
 *   `BETTER_AUTH_SECRET` and `TOKEN_HASH_KEY` when those Worker secrets aren't set (Platform §16,
 *   TDD §8.1). The key is inserted if absent and read back in one synchronous step, with no `await` in
 *   between, so concurrent callers from any isolate converge on the first value written, and the write
 *   is durable before the RPC returns (output gate). Values never leave this object except as the RPC
 *   result to the Worker: never logged, never copied to D1.
 *
 * - `recordKeySource(name, source)`: remembers which source each key last resolved from (in `meta`),
 *   and returns the previous one when it changed, so the Worker can log the switch (a Worker secret set
 *   or deleted on a running workspace signs everyone out or invalidates links, Platform §16).
 *
 * The class is never renamed or deleted (TDD §6.5): losing its storage signs everyone out.
 */
export class SystemObject extends CoreDurableObject {
  protected override migrations(): readonly DoMigration[] {
    return SYSTEM_MIGRATIONS;
  }

  ping(): Promise<RpcResult<{ schemaVersion: number }>> {
    return this.rpc(() => ok({ schemaVersion: this.schemaVersion }));
  }

  generatedKey(name: GeneratedKeyName): Promise<RpcResult<{ value: string }>> {
    return this.rpc(() => {
      // The name comes over RPC: check it even though the type says it's one of ours.
      if (!isGeneratedKeyName(name)) return err(apiError("validation_failed", "Unknown generated key."));
      this.sql.exec(
        "INSERT INTO generated_keys (name, value, created_at) VALUES (?, ?, ?) ON CONFLICT (name) DO NOTHING",
        name,
        randomKey(),
        Date.now(),
      );
      const row = this.sql.exec<{ value: string }>("SELECT value FROM generated_keys WHERE name = ?", name).one();
      return ok({ value: row.value });
    });
  }

  recordKeySource(name: GeneratedKeyName, source: RecordedKeySource): Promise<RpcResult<KeySourceChange>> {
    return this.rpc(() => {
      if (!isGeneratedKeyName(name) || (source !== "worker_secret" && source !== "generated")) {
        return err(apiError("validation_failed", "Unknown key or source."));
      }
      const key = `key_source:${name}`;
      const match = SOURCE_PATTERN.exec(this.getMeta(key) ?? "");
      if (match?.[1] === source) return ok({ previous: null });
      this.setMeta(key, `${source}:${Date.now()}`);
      return ok({
        previous: match ? { source: match[1] as RecordedKeySource, since: Number(match[2]) } : null,
      });
    });
  }
}

const SOURCE_PATTERN = /^(worker_secret|generated):(\d+)$/;

const SYSTEM_MIGRATIONS: readonly DoMigration[] = [
  {
    version: 1,
    description: "record creation time",
    up(sql) {
      sql.exec("INSERT OR IGNORE INTO meta (key, value) VALUES ('created_at', ?)", String(Date.now()));
    },
  },
  {
    version: 2,
    description: "keys generated by the Worker",
    up(sql) {
      // Expand only, safe to re-run (TDD §2.2, §6.5).
      sql.exec(`CREATE TABLE IF NOT EXISTS generated_keys (
        name TEXT PRIMARY KEY,
        value TEXT NOT NULL,
        created_at INTEGER NOT NULL
      )`);
    },
  },
];
