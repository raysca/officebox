// Extracts hash-wasm's embedded argon2 and blake2b WebAssembly binaries into src/wasm/*.wasm.
//
// Why: hash-wasm ships its WASM as base64 strings and calls WebAssembly.compile(bytes) at runtime. Workers forbid
// runtime code generation ("Wasm code generation disallowed by embedder"), so the binaries must instead be
// imported as modules, which Wrangler compiles at upload time. See src/argon2-shim.ts.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const src = readFileSync(join(dirname(require.resolve("hash-wasm/package.json")), "dist/index.esm.js"), "utf8");
const outDir = join(root, "src/wasm");
mkdirSync(outDir, { recursive: true });

const sizes = [];
for (const want of ["argon2", "blake2b"]) {
  const m = src.match(new RegExp(`var name(\\$\\w+) = "${want}";\\s*var data\\1 = "([A-Za-z0-9+/=]+)";`));
  if (!m) throw new Error(`could not find ${want} in hash-wasm`);
  const bytes = Buffer.from(m[2], "base64");
  writeFileSync(join(outDir, `${want}.wasm`), bytes);
  sizes.push(`export const ${want.toUpperCase()}_WASM_BYTES = ${bytes.length};`);
  console.log(`src/wasm/${want}.wasm  ${bytes.length} bytes`);
}
writeFileSync(join(outDir, "sizes.ts"), `// Generated by scripts/extract-wasm.mjs\n${sizes.join("\n")}\n`);
